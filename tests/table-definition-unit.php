<?php
declare(strict_types=1);
require_once dirname(__DIR__) . '/app/src/bootstrap.php';

use Govern\ApiException;
use Govern\Database;
use Govern\PostgresSqlScript;
use Govern\SqlScript;
use Govern\TableDefinition;

$checks = 0;
$assert = static function (bool $condition, string $message) use (&$checks): void {
    if (!$condition) throw new RuntimeException($message);
    $checks++;
};
$column = static fn (string $name = 'label', string $type = 'text'): array => ['name' => $name, 'type' => $type,
    'nullable' => true, 'primary' => false, 'generated' => false, 'default' => ['mode' => 'none']];
$compile = static fn (array $columns, string $engine = 'mariadb', string $name = 'notes'): array
    => TableDefinition::compile(['name' => $name, 'columns' => $columns], $engine, 'research', 'public');
$reject = static function (array $input, string $code = 'table_definition_column') use ($assert): void {
    try { TableDefinition::compile($input, 'mariadb', 'research', 'public'); }
    catch (ApiException $error) {
        $assert($error->errorCode === $code && $error->status === 422, 'Stable rejection: ' . $code);
        return;
    }
    throw new RuntimeException('Expected table definition rejection: ' . $code);
};
$definition = static fn (array $columns): array => ['name' => 'notes', 'columns' => $columns];

foreach (['mariadb', 'postgres'] as $engine) {
    $plain = $compile([$column()], $engine);
    $assert($plain['definition']['columns'][0]['default'] === ['mode' => 'none'], 'No implicit default is invented.');
    $assert($plain['definition']['columns'][0]['nullable'] === true, 'The initial column allows NULL.');
    $assert(!str_contains($plain['sql'], 'IF NOT EXISTS'), 'No occupied table can be adopted.');
    $assert(!str_contains($plain['sql'], 'DROP') && !str_contains($plain['sql'], 'ALTER'), 'A basic definition only creates a table.');
    $assert(str_contains($plain['sql'], $engine === 'mariadb' ? '`research`.`notes`' : '"public"."notes"'), 'DDL explicitly names the scoped namespace.');
    $assert(str_contains($plain['sql'], $engine === 'mariadb' ? 'LONGTEXT' : 'text'), 'Text uses the documented engine type.');
    $id = [...$column('id', 'whole'), 'nullable' => false, 'primary' => true, 'generated' => true];
    $built = $compile([$id, $column()], $engine);
    $assert(str_contains($built['sql'], $engine === 'mariadb' ? 'AUTO_INCREMENT' : 'GENERATED BY DEFAULT AS IDENTITY'), 'Generated identity uses native engine syntax.');
    $assert(substr_count($built['sql'], 'PRIMARY KEY') === 1, 'One generated primary key is declared.');
    $literal = [...$column(), 'default' => ['mode' => 'literal', 'value' => "a'; DROP TABLE previous; -- \\ path\nnew line"]];
    $quoted = $compile([$literal], $engine);
    $parts = $engine === 'postgres' ? PostgresSqlScript::split($quoted['sql']) : SqlScript::split($quoted['sql'], Database::SQL_MODE);
    $assert(count($parts) === 1, 'Quotes, semicolons, comments and backslashes inside a literal cannot create another statement.');
    $assert($quoted['definition']['columns'][0]['default']['value'] === $literal['default']['value'], 'Text literal bytes stay exact in the reviewed definition.');
}

$all = [$column('body'), $column('amount', 'whole'), [...$column('money', 'decimal'), 'precision' => 18, 'scale' => 8],
    $column('enabled', 'boolean'), $column('day', 'date'), $column('observed_at', 'datetime')];
$assert(count($compile($all)['definition']['columns']) === 6, 'All six initial type families compile.');
foreach (['9223372036854775807', '-9223372036854775808'] as $value) {
    $built = $compile([[...$column('amount', 'whole'), 'default' => ['mode' => 'literal', 'value' => $value]]]);
    $assert(str_contains($built['sql'], $value), 'Whole-number boundary remains exact without a floating point conversion.');
}
$decimal = $compile([[...$column('amount', 'decimal'), 'precision' => 30, 'scale' => 8,
    'default' => ['mode' => 'literal', 'value' => '1234567890123456789012.12345678']]]);
$assert(str_contains($decimal['sql'], '1234567890123456789012.12345678'), 'High precision decimal remains exact.');
$assert(str_contains($compile([[...$column('enabled', 'boolean'), 'default' => ['mode' => 'literal', 'value' => false]]])['sql'], 'DEFAULT FALSE'), 'Boolean false is a deliberate literal.');
$assert(str_contains($compile([[...$column('day', 'date'), 'default' => ['mode' => 'literal', 'value' => '2028-02-29']]])['sql'], '2028-02-29'), 'Real leap day is accepted.');
$assert($compile([[...$column('at', 'datetime'), 'default' => ['mode' => 'literal', 'value' => '2028-02-29T23:59:59.123456']]])['definition']['columns'][0]['default']['value'] === '2028-02-29 23:59:59.123456', 'Datetime is explicitly normalized without a stored timezone.');
$assert(str_contains($compile([[...$column(), 'default' => ['mode' => 'null']]])['sql'], 'DEFAULT NULL'), 'Explicit NULL differs from no explicit default.');
$assert(str_contains($compile([[...$column(), 'default' => ['mode' => 'literal', 'value' => '']]])['sql'], "DEFAULT ''"), 'Empty text remains an empty text literal.');

foreach (['', 'MixedCase', 'bad-name', '1notes', '_govern_secret', str_repeat('a', 64), "bad\0name"] as $name) {
    $reject(['name' => $name, 'columns' => [$column()]], 'table_definition_name');
}
$reject(['name' => 'notes', 'columns' => []], 'table_definition_invalid');
$reject(['name' => 'notes', 'columns' => array_fill(0, 257, $column())], 'table_definition_invalid');
$reject([...$definition([$column()]), 'sql' => 'DROP TABLE previous'], 'table_definition_invalid');
$reject($definition([[$column()]]));
$reject($definition([$column(), $column()]));
$reject($definition([[...$column(), 'nullable' => 'true']]));
$reject($definition([[...$column(), 'type' => 'text); DROP TABLE previous; --']]));
$reject($definition([[...$column(), 'primary' => true, 'nullable' => false]]));
$reject($definition([[...$column('one', 'whole'), 'primary' => true, 'nullable' => false], [...$column('two', 'whole'), 'primary' => true, 'nullable' => false]]));
$reject($definition([[...$column('id', 'whole'), 'generated' => true]]));
$reject($definition([[...$column('id', 'whole'), 'generated' => true, 'primary' => true, 'nullable' => false, 'default' => ['mode' => 'literal', 'value' => '1']]]));
$reject($definition([[...$column(), 'precision' => 12]]));
$reject($definition([[...$column('amount', 'decimal'), 'precision' => 12, 'scale' => 13]]));
$reject($definition([[...$column(), 'nullable' => false, 'default' => ['mode' => 'null']]]), 'table_definition_default');
$reject($definition([[...$column(), 'default' => ['mode' => 'expression', 'value' => 'CURRENT_TIMESTAMP']]]), 'table_definition_default');
$reject($definition([[...$column(), 'default' => ['mode' => 'none', 'value' => 'hidden']]]), 'table_definition_default');
foreach ([['whole', '9223372036854775808'], ['whole', '-9223372036854775809'], ['whole', '1.0'], ['whole', 1.1],
    ['decimal', '1e8'], ['decimal', '1.234'], ['boolean', '0'], ['boolean', 'TRUE'], ['date', '2027-02-29'],
    ['date', '0001-01-01'], ['datetime', '2026-11-04 24:00:00'], ['datetime', '2026-11-04 10:00:00Z'], ['text', "\xff"]] as [$type, $value]) {
    $reject($definition([[...$column('value', $type), 'default' => ['mode' => 'literal', 'value' => $value]]]), 'table_definition_default');
}

echo "PASS: $checks native table definition boundary and literal checks.\n";
