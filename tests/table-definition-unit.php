// Inject only the existing adapter boundary. This exercises the service outcome
// handling without requiring a database or changing the production constructor.
final class DefinitionTestStatement extends PDOStatement
{
    private mixed $value = null;
    public function __construct(private readonly Closure $read) {}
    public function execute(?array $params = null): bool { $this->value = ($this->read)($params); return true; }
    public function fetchColumn(int $column = 0): mixed { return $this->value; }
}
final class DefinitionTestConnection extends PDO
{
    public array $reads = [];
    public array $executed = [];
    public array $counts = [0, 0, 1];
    public ?PDOException $ddlFailure = null;
    public ?Throwable $verificationFailure = null;
    public bool $discarded = false;
    public function __construct() {}
    public function prepare(string $query, array $options = []): PDOStatement|false
    {
        return new DefinitionTestStatement(function (?array $params) use ($query): mixed {
            $this->reads[] = ['sql' => $query, 'params' => $params];
            if ($this->discarded && $this->verificationFailure !== null) throw $this->verificationFailure;
            if ($this->counts === []) throw new RuntimeException('Unexpected metadata read.');
            return array_shift($this->counts);
        });
    }
    public function exec(string $statement): int|false
    {
        $this->executed[] = $statement;
        if ($this->ddlFailure !== null) throw $this->ddlFailure;
        return 0;
    }
}
final class DefinitionTestAdapter implements DatabaseAdapter
{
    public int $scriptCalls = 0;
    public ?Throwable $connectionFailure = null;
    public function __construct(public readonly DefinitionTestConnection $connection) {}
    public function reader(): PDO { return $this->connection; }
    public function writer(): PDO { throw new RuntimeException('Table creation used the row writer.'); }
    public function scriptConnection(): PDO
    {
        $this->scriptCalls++;
        if ($this->connectionFailure !== null) throw $this->connectionFailure;
        return $this->connection;
    }
    public function discardReader(): void { $this->connection->discarded = true; }
    public function databaseNames(): array { return ['research']; }
}
$service = static function (string $engine = 'mariadb', string $schema = 'public', string $name = 'research'): array {
    $db = new Database(['engine' => $engine, 'name' => $name, 'schema' => $schema]);
    $connection = new DefinitionTestConnection();
    $adapter = new DefinitionTestAdapter($connection);
    (new ReflectionProperty(Database::class, 'adapter'))->setValue($db, $adapter);
    return [new TableDefinition($db), $connection, $adapter];
};
$serviceReject = static function (callable $action, string $code, int $status) use ($assert): void {
    try { $action(); }
    catch (ApiException $error) {
        $assert($error->errorCode === $code && $error->status === $status,
            'Expected service result ' . $code . ', got ' . $error->errorCode);
        return;
    }
    throw new RuntimeException('Expected service result ' . $code);
};
$pdoError = static function (string $state, int $number = 0): PDOException {
    $error = new PDOException('Simulated database outcome.');
    (new ReflectionProperty(Exception::class, 'code'))->setValue($error, $state);
    $error->errorInfo = [$state, $number, 'Simulated database outcome.'];
    return $error;
};
$simple = $definition([$column()]);
foreach (['mariadb', 'postgres'] as $engine) {
    [$builder, $connection, $adapter] = $service($engine);
    $preview = $builder->preview($simple);
    $assert($connection->executed === [] && $adapter->scriptCalls === 0, 'Preview never opens a write session.');
    $created = $builder->create(['definition' => $preview['definition'], 'definition_token' => $preview['definition_token']]);
    $assert($connection->executed === [$preview['sql']] && $adapter->scriptCalls === 1, 'Create executes exactly the reviewed statement once through the SQL connection.');
    $assert($created['created'] && $created['verified'] && !isset($created['definition_token']), 'Confirmed creation is separate from metadata verification.');
    $assert($created['scope_key'] === ($engine === 'mariadb' ? 'research' : 'postgres:research:public'), 'The result retains the complete selected scope.');
    $assert($connection->discarded && str_contains($connection->reads[2]['sql'], "table_type = 'BASE TABLE'"), 'Readback uses a fresh reader and verifies a real table, not another occupied name.');

    [$occupied, $occupiedConnection, $occupiedAdapter] = $service($engine);
    $occupiedConnection->counts = [1];
    $serviceReject(static fn () => $occupied->preview($simple), 'table_definition_exists', 409);
    $assert($occupiedAdapter->scriptCalls === 0, 'An occupied name is rejected before any SQL write connection.');

    [$changed, $changedConnection, $changedAdapter] = $service($engine);
    $review = $changed->preview($simple);
    $serviceReject(static fn () => $changed->create(['definition' => [...$simple, 'name' => 'other_name'],
        'definition_token' => $review['definition_token']]), 'table_definition_changed', 409);
    $assert($changedAdapter->scriptCalls === 0 && $changedConnection->executed === [], 'A changed definition cannot execute the old reviewed SQL.');
}

