$assert = static function (bool $condition, string $message) use (&$checks): void {
    if (!$condition) throw new RuntimeException($message);
    $checks++;
};
$column = static fn (string $name = 'label', string $type = 'text'): array => ['name' => $name, 'type' => $type,
    'nullable' => true, 'primary' => false, 'generated' => false, 'default' => ['mode' => 'none']];
$compile = static fn (array $columns, string $engine = 'mariadb', string $name = 'notes'): array
    => TableDefinition::compile(['name' => $name, 'columns' => $columns], $engine, 'research', 'public');
$reject = static function (array $input, string $code = 'table_definition_column') use ($assert): void {
    try { TableDefinition::compile($input, 'mariadb', 'research', 'public'); }
    catch (ApiException $error) {
        $assert($error->errorCode === $code && $error->status === 422, 'Stable rejection: ' . $code);
        return;
    }
    throw new RuntimeException('Expected table definition rejection: ' . $code);
};
$definition = static fn (array $columns): array => ['name' => 'notes', 'columns' => $columns];

foreach (['mariadb', 'postgres'] as $engine) {
    $plain = $compile([$column()], $engine);
    $assert($plain['definition']['columns'][0]['default'] === ['mode' => 'none'], 'No implicit default is invented.');
    $assert($plain['definition']['columns'][0]['nullable'] === true, 'The initial column allows NULL.');
    $assert(!str_contains($plain['sql'], 'IF NOT EXISTS'), 'No occupied table can be adopted.');
    $assert(!str_contains($plain['sql'], 'DROP') && !str_contains($plain['sql'], 'ALTER'), 'A basic definition only creates a table.');
    $assert(str_contains($plain['sql'], $engine === 'mariadb' ? '`research`.`notes`' : '"public"."notes"'), 'DDL explicitly names the scoped namespace.');
    $assert(str_contains($plain['sql'], $engine === 'mariadb' ? 'LONGTEXT' : 'text'), 'Text uses the documented engine type.');
    $id = [...$column('id', 'whole'), 'nullable' => false, 'primary' => true, 'generated' => true];
    $built = $compile([$id, $column()], $engine);
    $assert(str_contains($built['sql'], $engine === 'mariadb' ? 'AUTO_INCREMENT' : 'GENERATED BY DEFAULT AS IDENTITY'), 'Generated identity uses native engine syntax.');
    $assert(substr_count($built['sql'], 'PRIMARY KEY') === 1, 'One generated primary key is declared.');
    $literal = [...$column(), 'default' => ['mode' => 'literal', 'value' => "a'; DROP TABLE previous; -- \\ path\nnew line"]];
    $quoted = $compile([$literal], $engine);
    $parts = $engine === 'postgres' ? PostgresSqlScript::split($quoted['sql']) : SqlScript::split($quoted['sql'], Database::SQL_MODE);
    $assert(count($parts) === 1, 'Quotes, semicolons, comments and backslashes inside a literal cannot create another statement.');
    $assert($quoted['definition']['columns'][0]['default']['value'] === $literal['default']['value'], 'Text literal bytes stay exact in the reviewed definition.');
}

