#!/usr/bin/env python3
"""Check PostgreSQL role upgrades only in the disposable govern_pg database."""
import argparse
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--confirm-project', required=True)
parser.add_argument('--confirm-database', required=True, choices=['govern_pg'])
parser.add_argument('--env-file')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
prefix = ['docker', 'compose']
if args.env_file:
    prefix += ['--env-file', args.env_file]
prefix += ['--project-name', args.confirm_project, '--profile', 'postgres']
checks = 0


def check(condition, message):
    global checks
    if not condition:
        raise AssertionError(message)
    checks += 1


def sql(statement, role='admin'):
    connection = {
        'admin': '--username "$POSTGRES_USER"',
        'reader': 'PGPASSWORD="$PG_READ_PASSWORD" psql',
        'writer': 'PGPASSWORD="$PG_PASSWORD" psql',
    }
    if role == 'admin':
        client = 'exec psql -X -qAt ' + connection[role]
    else:
        user = 'PG_READ_USER' if role == 'reader' else 'PG_USER'
        client = connection[role] + ' -X -qAt --host=127.0.0.1 --username "$' + user + '"'
    client += ' --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1'
    return subprocess.run(prefix + ['exec', '-T', 'postgres', 'sh', '-c', client],
                          input=statement, text=True, capture_output=True, cwd=root)


def provision(*overrides):
    return subprocess.run(prefix + ['run', '--rm', '-T', '--no-deps', *overrides, 'postgres-access'],
                          text=True, capture_output=True, cwd=root)


check(sql('SELECT current_database();').stdout.strip() == args.confirm_database,
      'Provisioning checks are restricted to the confirmed disposable database.')
fixture = sql(r'''
BEGIN;
CREATE SCHEMA IF NOT EXISTS archive;
CREATE SCHEMA govern_provision_excluded;
CREATE TABLE public.govern_provision_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text NOT NULL);
CREATE TABLE archive.govern_provision_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text NOT NULL);
CREATE TABLE govern_provision_excluded.probe (id integer PRIMARY KEY);
\getenv writer PG_USER
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO :"writer";
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO :"writer";
COMMIT;
''')
check(fixture.returncode == 0, 'Isolated permission fixtures are created without replacing existing objects.')
try:
    check(provision().returncode == 0, 'Existing database volumes gain the scoped writer idempotently.')
    check(provision().returncode == 0, 'Reapplying access preserves both application accounts.')
    check(sql('SHOW transaction_read_only;', 'reader').stdout.strip() == 'on',
          'The reader still starts in a genuinely read-only session.')
    check(sql('CREATE TABLE public.govern_provision_default_probe (id bigserial PRIMARY KEY, label text);').returncode == 0,
          'The bootstrap owner can create a new table after provisioning.')
    result = sql("INSERT INTO public.govern_provision_default_probe (label) VALUES ('new default grants') RETURNING id;", 'writer')
    check(result.returncode == 0 and result.stdout.strip() == '1',
          'New administrator-owned tables and sequences inherit the scoped writer grants.')
    check(sql('TRUNCATE public.govern_provision_default_probe;', 'writer').returncode != 0,
          'An older broad default grant is narrowed to row operations on new tables.')
    for schema in ['public', 'archive']:
        result = sql(f"INSERT INTO {schema}.govern_provision_probe (label) VALUES ('first') RETURNING id;", 'writer')
        check(result.returncode == 0 and result.stdout.strip() == '1',
              'Writer inserts with sequence-generated identity in ' + schema + '.')
        result = sql(f"UPDATE {schema}.govern_provision_probe SET label = 'changed' WHERE id = 1 RETURNING label;", 'writer')
        check(result.returncode == 0 and result.stdout.strip() == 'changed', 'Writer can update in ' + schema + '.')
        check(sql(f'SELECT count(*) FROM {schema}.govern_provision_probe;', 'reader').stdout.strip() == '1',
              'Reader sees the writer result in ' + schema + '.')
        check(sql(f'SET default_transaction_read_only = off; DELETE FROM {schema}.govern_provision_probe WHERE id = 1;', 'reader').returncode != 0,
              'The independent reader cannot delete in ' + schema + '.')
        result = sql(f'DELETE FROM {schema}.govern_provision_probe WHERE id = 1 RETURNING id;', 'writer')
        check(result.returncode == 0 and result.stdout.strip() == '1', 'Writer can delete in ' + schema + '.')
    for statement in ['CREATE TABLE public.govern_forbidden_probe (id integer);',
                      'CREATE SCHEMA govern_forbidden_probe;',
                      'DROP TABLE public.govern_provision_probe;',
                      'TRUNCATE public.govern_provision_probe;',
                      'SELECT * FROM govern_provision_excluded.probe;']:
        check(sql(statement, 'writer').returncode != 0, 'Writer is denied DDL, truncate and unconfigured schemas.')
    check(provision('-e', 'PG_PASSWORD=deliberately-different-provisioning-test-password').returncode != 0,
          'Changing the environment password reports a mismatch instead of resetting an existing role.')
    check(sql('SELECT 1;', 'writer').stdout.strip() == '1', 'The original writer password remains valid.')
    check(provision('-e', 'PG_USER=postgres').returncode != 0,
          'Bootstrap credentials cannot be configured as the writer.')
finally:
    sql('DROP TABLE IF EXISTS public.govern_provision_default_probe; DROP TABLE public.govern_provision_probe; DROP TABLE archive.govern_provision_probe; DROP SCHEMA govern_provision_excluded CASCADE;')

print(f'PostgreSQL provisioning checks: {checks} passed.')
