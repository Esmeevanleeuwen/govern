    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label text NOT NULL,
    amount numeric(30,2) NOT NULL DEFAULT 0,
    nullable_text text,
    default_text text DEFAULT 'server default',
    payload bytea,
    unsupported_values integer[] DEFAULT ARRAY[1,2],
    generated_label text GENERATED ALWAYS AS (label || '!') STORED
);
