<?php
declare(strict_types=1);
/** Schema round-trip ONLY in the explicitly isolated govern_pg fixture database. */
require_once dirname(__DIR__) . '/app/src/bootstrap.php';
use Govern\BackupException;
use Govern\BackupInputException;
use Govern\Config;
use Govern\ConnectionScope;
use Govern\Database;
use Govern\PostgresBackupService;
$base = Config::fromEnvironment();
$options = getopt('', ['confirm-database:']);
if (($base['postgres']['name'] ?? '') !== 'govern_pg' || ($options['confirm-database'] ?? '') !== 'govern_pg'
    || !in_array('archive', $base['postgres']['schemas'] ?? [], true)) {
    fwrite(STDERR, "Confirm isolated govern_pg with public/archive fixtures.\n"); exit(2);
}
$config = (new ConnectionScope($base))->select('govern_pg', 'postgres', 'archive');
$pdo = (new Database($config))->scriptConnection();
$backup = new PostgresBackupService($config);
$passed = 0;
$assert = static function (bool $condition, string $message) use (&$passed): void {
    if (!$condition) throw new RuntimeException($message); $passed++;
};
$reject = static function (callable $action, string $code) use ($assert): void {
    try { $action(); }
    catch (BackupException | BackupInputException $exception) { $assert($exception->errorCode === $code, $code . ': received ' . $exception->errorCode); return; }
    throw new RuntimeException('Expected ' . $code);
};
$quote = static fn (string $name): string => '"' . str_replace('"','""',$name) . '"';
$owner = static fn (): string => (string) $pdo->query("SELECT pg_catalog.pg_get_userbyid(nspowner) FROM pg_catalog.pg_namespace WHERE nspname='archive'")->fetchColumn();
$originalOwner = $owner();
$baseline = $backup->create('Isolated baseline before checkpoint tests');
try {
    $pdo->exec('CREATE TABLE archive.govern_backup_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount numeric(30,2) NOT NULL, label text NOT NULL, payload bytea, derived text GENERATED ALWAYS AS(label || chr(33)) STORED)');
    $pdo->exec("INSERT INTO archive.govern_backup_probe (amount,label,payload) VALUES (123456789012345678901234.12,'original',decode('00ff41','hex'))");
    $pdo->exec('CREATE VIEW archive.govern_backup_view AS SELECT id,label FROM archive.govern_backup_probe');
    $snapshot = $backup->create('Exact original row');
    $assert($snapshot['restore_available'] === true, 'A self-contained schema offers restore immediately.');
    $assert($snapshot['database'] === 'govern_pg' && $snapshot['schema'] === 'archive' && $snapshot['format'] === 'postgres-custom-v1', 'Descriptor binds native binary format and schema.');
    $download = $backup->download($snapshot['id']);
    $assert(substr((string) file_get_contents($download['path']),0,5) === 'PGDMP', 'Download contains a native custom archive.');
    $assert(hash_file('sha256',$download['path']) === $snapshot['sha256'], 'Downloaded bytes match checkpoint digest.');
    $reject(static fn () => $backup->restore($snapshot['id'],'govern_pg'), 'restore_confirmation_invalid');
    $pdo->exec("UPDATE archive.govern_backup_probe SET label='changed',amount=1 WHERE id=1");
    $pdo->exec('CREATE TABLE archive.govern_backup_extra(id integer)');
    $restorer = $quote($config['restore_user'] ?? 'govern_pg_restore');
    $readerRole = $quote($config['read_user']);
    $pdo->exec('SET ROLE ' . $restorer);
    $pdo->exec('ALTER DEFAULT PRIVILEGES IN SCHEMA archive GRANT ALL ON TABLES TO ' . $readerRole);
    $pdo->exec('ALTER DEFAULT PRIVILEGES GRANT ALL ON SEQUENCES TO ' . $readerRole);
    $pdo->exec('RESET ROLE');
    $result = $backup->restore($snapshot['id'],'govern_pg.archive');
    $assert($result['restored'] === $snapshot['id'] && is_array($result['safety_snapshot']), 'Restore saves a separate safety checkpoint.');
    $assert($result['safety_snapshot']['id'] !== $snapshot['id'], 'Safety copy is a separate artifact.');
    $row = $pdo->query("SELECT id::text,amount::text,label,encode(payload,'hex') AS payload,derived FROM archive.govern_backup_probe WHERE id=1")->fetch();
    $assert($row['amount'] === '123456789012345678901234.12' && $row['label'] === 'original' && $row['payload'] === '00ff41' && $row['derived'] === 'original!', 'Restore reads exact numeric, bytea and generated values back.');
    $assert($pdo->query("SELECT to_regclass('archive.govern_backup_extra')")->fetchColumn() === null, 'Newer objects disappear on restore.');
    $assert($pdo->query('SELECT label FROM archive.govern_backup_view WHERE id=1')->fetchColumn() === 'original', 'View relationships are restored.');
    $assert($owner() === $originalOwner, 'Original schema owner is preserved.');
    $restoreRole = $pdo->quote($config['restore_user'] ?? 'govern_pg_restore');
    $schemaRights = $pdo->query("SELECT pg_catalog.has_schema_privilege($restoreRole,'archive','USAGE')::text AS can_use,
        pg_catalog.has_schema_privilege($restoreRole,'archive','CREATE')::text AS can_create")->fetch();
    $assert($schemaRights['can_use'] === 'true' && $schemaRights['can_create'] === 'true',
        'Restoring the original owner retains both scoped restore privileges for later foreign-key restores.');
    $id = $pdo->query("INSERT INTO archive.govern_backup_probe(amount,label) VALUES(2,'after restore') RETURNING id::text")->fetchColumn();
    $assert($id === '2', 'Identity sequence retains its next value.');
    $reader = (new Database($config))->reader();
    $reader->exec('SET default_transaction_read_only=off');
    try { $reader->exec("UPDATE archive.govern_backup_probe SET label='reader mutation' WHERE id=1"); throw new RuntimeException('Reader acquired DML through default ACLs.'); }
    catch (PDOException $exception) { $assert($exception->getCode() === '42501', 'Reader DML is denied even after disabling session read-only.'); }
    try { $reader->query("SELECT nextval('archive.govern_backup_probe_id_seq')"); throw new RuntimeException('Reader acquired sequence mutation.'); }
    catch (PDOException $exception) { $assert($exception->getCode() === '42501', 'Reader sequence SELECT never grants nextval.'); }
    $reader = null;
    $pdo->exec('CREATE VIEW public.govern_backup_external AS SELECT id FROM archive.govern_backup_probe');
    $blocked = $backup->create('Download remains available with external dependents');
    $assert($blocked['restore_available'] === false, 'A valid export honestly flags unavailable schema restoration.');
    $listed = array_column($backup->list(), null, 'id');
    $assert($listed[$snapshot['id']]['restore_available'] === false, 'List recomputes current restore eligibility.');
    $reject(static fn () => $backup->restore($snapshot['id'],'govern_pg.archive'), 'postgres_snapshot_dependencies');
    $assert($pdo->query("SELECT to_regclass('public.govern_backup_external')")->fetchColumn() !== null, 'Refused restore preserves cross-schema dependents.');
    $pdo->exec('DROP VIEW public.govern_backup_external');
    $listed = array_column($backup->list(), null, 'id');
    $assert($listed[$blocked['id']]['restore_available'] === true, 'Removing the dependency reenables older exports.');
    $pdo->exec('CREATE TABLE archive.govern_backup_auth_log(session_name text,current_name text)');
    $body = "BEGIN IF current_setting('application_name')='govern-checkpoints-restore' THEN EXECUTE 'RESET ROLE'; INSERT INTO archive.govern_backup_auth_log VALUES(session_user,current_user); END IF; RETURN true; END";
    $pdo->exec('CREATE FUNCTION archive.govern_backup_auth_fn() RETURNS boolean LANGUAGE plpgsql AS ' . $pdo->quote($body));
    $pdo->exec('CREATE TABLE archive.govern_backup_auth(id integer CHECK(archive.govern_backup_auth_fn()))');
    $pdo->exec('INSERT INTO archive.govern_backup_auth VALUES(1)');
    $auth = $backup->create('Restricted authenticated restore regression');
    $backup->restore($auth['id'],'govern_pg.archive');
    $roles = $pdo->query('SELECT session_name,current_name FROM archive.govern_backup_auth_log')->fetch();
    $assert($roles['session_name'] === ($config['restore_user'] ?? 'govern_pg_restore')
        && $roles['current_name'] === $roles['session_name'], 'Archive CHECK code cannot RESET ROLE to administrator authentication.');
    $pdo->exec("CREATE FUNCTION archive.govern_backup_guard_fn() RETURNS boolean LANGUAGE plpgsql AS 'BEGIN IF current_setting(''application_name'')=''govern-checkpoints-restore'' THEN RAISE EXCEPTION ''intentional restore refusal''; END IF; RETURN true; END'");
    $pdo->exec('CREATE TABLE archive.govern_backup_guard(id integer CHECK(archive.govern_backup_guard_fn()))');
    $pdo->exec('INSERT INTO archive.govern_backup_guard VALUES(1)');
    $failing = $backup->create('Intentional transaction rollback fixture');
    $pdo->exec("UPDATE archive.govern_backup_probe SET label='must survive rollback' WHERE id=1");
    $reject(static fn () => $backup->restore($failing['id'],'govern_pg.archive'), 'postgres_restore_failed');
    $assert($pdo->query('SELECT label FROM archive.govern_backup_probe WHERE id=1')->fetchColumn() === 'must survive rollback', 'A failed restore rolls back earlier drops and data changes.');
    $assert($pdo->query('SELECT count(*)::text FROM archive.govern_backup_guard')->fetchColumn() === '1', 'Failed restore preserves original schema objects.');
    $assert($owner() === $originalOwner, 'Failure restores original schema ownership.');
    $schemaRights = $pdo->query("SELECT pg_catalog.has_schema_privilege($restoreRole,'archive','USAGE')::text AS can_use,
        pg_catalog.has_schema_privilege($restoreRole,'archive','CREATE')::text AS can_create")->fetch();
    $assert($schemaRights['can_use'] === 'true' && $schemaRights['can_create'] === 'true',
        'Failed restoration also retains both scoped restore privileges.');
    $publicConfig = (new ConnectionScope($base))->select('govern_pg','postgres','public');
    $reject(static fn () => (new PostgresBackupService($publicConfig))->restore($snapshot['id'],'govern_pg.public'), 'snapshot_missing');
} finally {
    $pdo->exec('RESET ROLE');
    $pdo->exec('DROP VIEW IF EXISTS public.govern_backup_external');
    $backup->restore($baseline['id'],'govern_pg.archive');
}
echo "PASS: $passed PostgreSQL checkpoint/restore/ACL/scope/rollback checks.\n";
